# julia -t 5 --project=scripts/paper scripts/paper/timing.jl [outdir]
#
# Cost of the 2D 4-body model on the 2+3+4-body benchmark (the training data of figures.jl), on all Julia threads,
# BLAS at its default: evaluation of its basis (DEGREES in setup.jl) per
# environment, as the wall time of the package's threaded evaluation of all test environments divided by their
# number (median of 9 passes), and the fit with λ by the evidence (fitcv, median of 3). The load average before and after is recorded.
# Writes OUT/numbers_timing.tex.

include(joinpath(@__DIR__, "setup.jl"))

loadavg() = parse(Float64, split(strip(read(`sysctl -n vm.loadavg`, String), ['{', '}', ' ']))[1])
machine() = strip(read(`sysctl -n machdep.cpu.brand_string`, String))
let load0 = loadavg()
    s = only(s for s in SWARMS if s.key == "mixed")
    b4() = only(m.basis for m in MODELS if m.key == "d4")()
    train, test = swarm_data(s.rule, TRAIN_SEEDS), swarm_data(s.rule, TEST_SEEDS)
    b = b4()
    envs = test[1]
    pass() = dACE.foreach_workspace((work, i) -> dACE.evaluate!(work, b, envs[i]), b, length(envs))   # the package's threaded evaluation
    pass()   # compile
    t_eval = median([@elapsed(pass()) for _ in 1:9]) / length(envs)
    fitcv(b4(), train[1][1:400], train[2][1:400])   # compile
    t_fit = median([@elapsed(fitcv(b4(), train...)) for _ in 1:3])
    load1 = loadavg()
    open(joinpath(OUT, "numbers_timing.tex"), "w") do io
        println(io, "% generated by scripts/paper/timing.jl on $(machine()), load average $load0 before, $load1 after")
        newcmd(name, val) = println(io, "\\newcommand{\\$name}{", val, "}")
        newcmd("costBasisFour", length(b))
        newcmd("costNeighbours", @sprintf("%.0f", mean(length.(envs))))
        newcmd("costEvalFour", @sprintf("%.0f", 1.0e6 * t_eval))
        newcmd("costFitFour", @sprintf("%.1f", t_fit))
        newcmd("costThreads", Threads.nthreads())
    end
    @printf("evaluation %.1f µs per environment, fit %.2f s on %d threads; load %.2f -> %.2f\n", 1e6t_eval, t_fit, Threads.nthreads(), load0, load1)
end
